const packs: Record<Lang, Record<CopyKey, string>> = { az, tr, en, ru, ar };

export function text(lang: Lang, key: CopyKey) {
  return packs[lang][key] ?? az[key];
}

export function isLang(value: unknown): value is Lang {
  return LANGS.some((item) => item.id === value);
}

export function notebookCount(n: number, lang: Lang) {
  if (lang === "en") return n === 1 ? "1 notebook" : `${n} notebooks`;
  if (lang === "tr") return n === 1 ? "1 defter" : `${n} defter`;
  if (lang === "ru") return `${n} тетр.`;
  if (lang === "ar") return n === 1 ? "دفتر واحد" : `${n} دفاتر`;
  return n === 1 ? "1 dəftər" : `${n} dəftər`;
}
